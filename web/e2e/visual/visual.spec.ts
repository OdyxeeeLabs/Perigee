import { expect, test, type Page } from "@playwright/test";

/**
 * Visual regression suite — issue #707.
 *
 * ## What this actually protects
 *
 * Not appearance. The regressions that matter for accessibility are specific
 * and mostly invisible in a pixel diff:
 *
 * - A focus ring removed by a Tailwind refactor (`focus:outline-none` without
 *   a replacement) — the element looks identical until it is focused.
 * - A contrast fix reverted, or a token re-tuned for one theme and not the
 *   other.
 * - A `forced-colors` / high-contrast override dropped, which only shows under
 *   an emulation the eye misses locally.
 * - An `aria-hidden` wrapper accidentally swallowing a focusable control.
 *
 * So the suite is arranged around *states* — default, focus-visible, high
 * contrast, reduced motion, RTL, each navigation layer — not around pages. A
 * page-level screenshot of the default state catches none of the above.
 *
 * ## Why focus is a separate project rather than a modifier
 *
 * A focused screenshot needs a deterministic focus target. `page.keyboard.press`
 * on a real page lands on whatever the first control happens to be, which
 * changes whenever the header changes. The views below target focus by a
 * stable selector, so the baseline means something.
 *
 * ## Baselines
 *
 * `web/e2e/visual/__screenshots__/<project>/<platform>/…` are generated by
 * `yarn playwright.visual:update` and reviewed as a binary diff. They are
 * platform-specific by construction — see the `snapshotPathTemplate` comment
 * in playwright.visual.config.ts.
 *
 * ## Requires `@playwright/test`, which is not declared
 *
 * See docs/accessibility/visual-regression.md.
 */

/** Freeze anything that would make a screenshot non-deterministic. */
async function stabilise(page: Page) {
  // Kill blinking carets and any looping animation.
  await page.addStyleTag({
    content: `*, *::before, *::after {
      animation-duration: 0s !important;
      animation-delay: 0s !important;
      transition-duration: 0s !important;
      caret-color: transparent !important;
    }`,
  });
  // Freeze the clock: relative timestamps ("3 minutes ago") otherwise differ
  // between the baseline run and the comparison run.
  await page.clock.install({ time: new Date("2026-01-15T10:30:00Z") });
  await page.emulateMedia({ reducedMotion: "reduce" });
}

/** Route every network call to a fixed, empty response. */
async function offline(page: Page) {
  await page.route("**/api/**", (route) =>
    route.fulfill({ status: 503, contentType: "application/json", body: "{}" }),
  );
}

test.describe("focus visibility", () => {
  test("the first focusable control has a visible ring", async ({ page }) => {
    await stabilise(page);
    await page.goto("/");
    // Targeting the skip link specifically: it is the first focusable element
    // on every page and the most commonly removed "invisible" control.
    const skipLink = page.getByRole("link", { name: /skip to content/i }).first();
    await skipLink.focus();
    await expect(skipLink).toBeFocused();
    await expect(page).toHaveScreenshot("focus-skip-link.png");
  });

  test("a button keeps its focus ring", async ({ page }) => {
    await stabilise(page);
    await page.goto("/");
    const button = page.getByRole("button").first();
    await button.focus();
    await expect(button).toBeFocused();
    await expect(page).toHaveScreenshot("focus-button.png");
  });
});

test.describe("high contrast", () => {
  test.use({ forcedColors: "active" });

  test("controls stay visible under forced colors", async ({ page }) => {
    await stabilise(page);
    await page.goto("/");
    await expect(page).toHaveScreenshot("forced-colors-home.png");
  });

  test("the manual high-contrast toggle is not the only path", async ({ page }) => {
    // The data-contrast="high" mapping is separate from forced-colors, and a
    // regression in one does not show up in the other.
    await stabilise(page);
    await page.goto("/");
    await page.evaluate(() => document.documentElement.setAttribute("data-contrast", "high"));
    await expect(page).toHaveScreenshot("manual-high-contrast-home.png");
  });
});

test.describe("navigation layers", () => {
  test("the command palette keeps focus inside it", async ({ page }) => {
    await stabilise(page);
    await page.goto("/");
    await page.keyboard.press("Control+k");
    await expect(page.getByRole("dialog").first()).toBeVisible();
    await expect(page).toHaveScreenshot("command-palette.png");
  });

  test("the mobile nav drawer at the mobile breakpoint", async ({ page }) => {
    await stabilise(page);
    await page.goto("/");
    const trigger = page.getByRole("button", { name: /open.*navigation|menu/i }).first();
    if (await trigger.count()) {
      await trigger.click();
      await expect(page).toHaveScreenshot("nav-drawer.png");
    }
  });
});

test.describe("offline and degraded states", () => {
  test("the network banner is visible when the API is down", async ({ page }) => {
    await stabilise(page);
    await offline(page);
    await page.goto("/");
    await expect(page).toHaveScreenshot("api-down.png", {
      // This state legitimately shows a cached timestamp.
      maxDiffPixelRatio: 0.02,
    });
  });
});

const ONBOARDING_ADDRESS = "GTESTFIXTURE0000000000000000000000000000000000000000000000";

type ManagerFixtureStatus = "none" | "pending" | "approved";

async function managerFixture(page: Page, status: ManagerFixtureStatus) {
  await page.addInitScript((address) => {
    const fakeWallet = {
      isConnected: () => true,
      getAddress: async () => address,
      getNetwork: async () => "Testnet SDF",
      signTransaction: async () => ({}),
    };
    Object.defineProperty(window, "freighter", {
      value: fakeWallet,
      configurable: true,
    });
    Object.defineProperty(window, "freighterApi", {
      value: fakeWallet,
      configurable: true,
    });
    localStorage.setItem("perigee_wallet_address", address);
    localStorage.setItem("perigee_wallet_id", "freighter");
    sessionStorage.setItem("perigee_wallet_id", "freighter");
    sessionStorage.removeItem("onboarding_draft");
  }, ONBOARDING_ADDRESS);

  await page.route("**/api/**", (route) =>
    route.fulfill({ status: 200, contentType: "application/json", body: "{}" }),
  );
  await page.route("**/managers/status/**", (route) => {
    if (route.request().method() === "OPTIONS") {
      return route.fulfill({
        status: 204,
        headers: {
          "access-control-allow-origin": "*",
          "access-control-allow-headers": "accept,content-type,x-api-version",
          "access-control-allow-methods": "GET, OPTIONS",
        },
      });
    }
    return route.fulfill({
      status: 200,
      contentType: "application/json",
      headers: { "access-control-allow-origin": "*" },
      body: JSON.stringify({ id: "mgr-fixture-1", status, message: "" }),
    });
  });
  await page.route("**/managers/register", (route) => {
    if (route.request().method() === "OPTIONS") {
      return route.fulfill({
        status: 204,
        headers: {
          "access-control-allow-origin": "*",
          "access-control-allow-headers": "accept,content-type,x-api-version",
          "access-control-allow-methods": "POST, OPTIONS",
        },
      });
    }
    return route.fulfill({
      status: 200,
      contentType: "application/json",
      headers: { "access-control-allow-origin": "*" },
      body: JSON.stringify({
        id: "mgr-fixture-1",
        stellar_address: ONBOARDING_ADDRESS,
        name: "Fixture Manager",
        email: "fixture@example.com",
        status: "pending",
        kyc_document_ref: "KYC-FIXTURE-1",
        notes: "",
        created_at: "2026-01-15T10:30:00Z",
        updated_at: "2026-01-15T10:30:00Z",
      }),
    });
  });
}

test.describe("manager onboarding", () => {
  test("initial registration state", async ({ page }) => {
    await stabilise(page);
    await managerFixture(page, "none");
    await page.goto("/managers/onboarding");
    await expect(page.getByTestId("onboarding-step")).toHaveAttribute(
      "data-step",
      "register",
    );
    await expect(
      page.getByRole("heading", { name: /register as a manager/i }),
    ).toBeVisible();
    await expect(page).toHaveScreenshot("onboarding-initial.png");
  });

  test("validation-error state", async ({ page }) => {
    await stabilise(page);
    await managerFixture(page, "none");
    await page.goto("/managers/onboarding");
    await page.getByLabel(/full name/i).fill("   ");
    await page.getByRole("button", { name: /submit registration/i }).click();
    await expect(page.getByTestId("onboarding-error")).toContainText(
      /name is required/i,
    );
    await expect(page).toHaveScreenshot("onboarding-validation-error.png");
  });

  test("completed state", async ({ page }) => {
    await stabilise(page);
    await managerFixture(page, "none");
    await page.goto("/managers/onboarding");
    await page.getByLabel(/full name/i).fill("Fixture Manager");
    await page.getByLabel("Email", { exact: true }).fill("fixture@example.com");
    await page.getByRole("button", { name: /submit registration/i }).click();
    await expect(page.getByTestId("onboarding-step")).toHaveAttribute(
      "data-step",
      "submitted",
    );
    await expect(page.getByTestId("onboarding-record")).toContainText(
      "mgr-fixture-1",
    );
    await expect(page).toHaveScreenshot("onboarding-completed.png");
  });
});

test.describe("small-screen data views", () => {
  for (const viewport of [
    { name: "phone", width: 360, height: 740 },
    { name: "tablet", width: 768, height: 1024 },
  ]) {
    test.describe(viewport.name, () => {
      test.use({ viewport: { width: viewport.width, height: viewport.height } });

      test("analytics table keeps its controls reachable", async ({ page }) => {
        await stabilise(page);
        await page.route("**/api/**", (route) =>
          route.fulfill({ status: 200, contentType: "application/json", body: "{}" }),
        );
        await page.goto("/analytics");
        await page.getByRole("button", { name: /live event stream/i }).click();
        await expect(
          page.getByRole("group", { name: /comparison date range/i }),
        ).toBeVisible();

        const hasNoPageOverflow = await page.evaluate(
          () =>
            document.documentElement.scrollWidth <=
            document.documentElement.clientWidth + 1,
        );
        expect(hasNoPageOverflow).toBe(true);

        const scrollRegions = page.locator('[role="region"][tabindex="0"]');
        const regions = await scrollRegions.count();
        for (let index = 0; index < regions; index += 1) {
          await scrollRegions.nth(index).focus();
          await expect(scrollRegions.nth(index)).toBeFocused();
        }

        await expect(page).toHaveScreenshot(
          `small-screen-analytics-${viewport.name}.png`,
        );
      });

      test("portfolio key values are readable without colour", async ({ page }) => {
        await stabilise(page);
        await page.addInitScript(() => {
          Math.random = () => 0.42;
          const fixed = Date.parse("2026-01-15T10:30:00Z");
          Date.now = () => fixed;
        });
        await page.route("**/api/**", (route) =>
          route.fulfill({ status: 200, contentType: "application/json", body: "{}" }),
        );
        await page.goto("/portfolio");

        await expect(page.getByTestId("comparison-range")).toBeVisible();
        await expect(page.getByTestId("range-label")).toContainText(/last 7 days/i);
        await expect(page.getByText(/^active$/i).first()).toBeVisible();
        await expect(page.getByText(/^locked$/i).first()).toBeVisible();

        const hasNoPageOverflow = await page.evaluate(
          () =>
            document.documentElement.scrollWidth <=
            document.documentElement.clientWidth + 1,
        );
        expect(hasNoPageOverflow).toBe(true);

        await expect(page).toHaveScreenshot(
          `small-screen-portfolio-${viewport.name}.png`,
        );
      });
    });
  }
});
